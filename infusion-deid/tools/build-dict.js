#!/usr/bin/env node
/* Build src/dict.js: a Bloom filter over vendor/names/english-words.txt (274,937 words, MIT).
 * Used only to answer "is this an ordinary dictionary word?" in the strict pass and the release scan.
 * False positive rate ~0.5%: an unknown word occasionally reads as a dictionary word (a miss, never an over-redaction). */
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..');
const words = fs.readFileSync(path.join(root, 'vendor/names/english-words.txt'), 'utf8').split(/\r?\n/).map((w) => w.trim().toLowerCase()).filter((w) => /^[a-z][a-z'\-]{1,}$/.test(w));
const n = words.length, p = 0.005;
const m = Math.ceil(-n * Math.log(p) / (Math.LN2 * Math.LN2)); const k = Math.round((m / n) * Math.LN2);
const bits = new Uint8Array(Math.ceil(m / 8));
const h1 = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; };
const h2 = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = (Math.imul(h, 33) ^ s.charCodeAt(i)) >>> 0; return (h | 1) >>> 0; };
for (const w of words) { const a = h1(w), b = h2(w); for (let i = 0; i < k; i++) { const x = (a + Math.imul(i, b)) >>> 0; const bit = x % m; bits[bit >> 3] |= 1 << (bit & 7); } }
const b64 = Buffer.from(bits).toString('base64');
const js = `/* Infusion De-ID — English dictionary Bloom filter (generated by tools/build-dict.js from an-array-of-english-words, MIT; do not edit) */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.DeIDDict = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const M = ${m}, K = ${k}, B64 = '${b64}';
  let bits = null;
  const load = () => { if (bits) return bits; const s = typeof atob === 'function' ? atob(B64) : Buffer.from(B64, 'base64').toString('binary'); bits = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) bits[i] = s.charCodeAt(i); return bits; };
  const h1 = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; };
  const h2 = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = (Math.imul(h, 33) ^ s.charCodeAt(i)) >>> 0; return (h | 1) >>> 0; };
  function has(word) {
    const w = String(word || '').toLowerCase(); if (!w) return false;
    const b = load(); const a = h1(w), c = h2(w);
    for (let i = 0; i < K; i++) { const x = (a + Math.imul(i, c)) >>> 0; const bit = x % M; if (!(b[bit >> 3] & (1 << (bit & 7)))) return false; }
    return true;
  }
  return { has, size: ${n} };
});
`;
fs.writeFileSync(path.join(root, 'src/dict.js'), js);
console.log(`dict: ${n} words, m=${m} bits, k=${k}, ${(Buffer.byteLength(js) / 1024).toFixed(0)} KB`);
