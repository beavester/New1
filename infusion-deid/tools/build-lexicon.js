#!/usr/bin/env node
/* Build src/biglex.js: a large, frequency-tiered name lexicon.
 *
 * Sources (vendor/names/, fetched by tools/fetch-names.sh; provenance in vendor/names/README.md):
 *   surnames.csv      US Census 2000 surnames with counts (public domain)
 *   baby-names.csv    SSA top-1000 baby names per year 1880-2008 (public domain)
 *   first-all.txt     smashew/NameDatabases first names, many countries (public domain)
 *   surnames-us.txt   smashew/NameDatabases US surnames (public domain)
 *   english-20k.txt   20k most common English words: a name that is also a word needs a cue
 *
 * Tiers:
 *   S2  strong surnames   census count >= 1000           -> may be tagged on their own
 *   S1  weak surnames     census 100..999 or list-only   -> need a second name token or a cue
 *   F2  strong first      SSA top-1000 names             -> may be tagged on their own
 *   F1  weak first        list-only                      -> need a second name token or a cue
 *   EN  English words     consulted by lexicon.js to decide which names are also ordinary words
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, 'vendor/names', f), 'utf8');
const norm = (s) => s.trim().toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
const ok = (s) => /^[a-z][a-z'\-]{2,24}$/.test(s);

const english = [...new Set(read('english-20k.txt').split(/\r?\n/).map(norm).filter((w) => /^[a-z]{2,}$/.test(w)))];
const census = new Map();
for (const line of read('surnames.csv').split(/\r?\n/).slice(1)) { const [name, , count] = line.split(','); const n = norm(name || ''); if (ok(n) && +count) census.set(n, +count); }
const listSur = new Set(read('surnames-us.txt').split(/\r?\n/).map(norm).filter(ok));
const ssa = new Set();
for (const line of read('baby-names.csv').split(/\r?\n/).slice(1)) { const parts = line.split(','); const n = norm((parts[1] || '').replace(/"/g, '')); if (ok(n)) ssa.add(n); }
const listFirst = new Set(read('first-all.txt').split(/\r?\n/).map(norm).filter(ok));

const S2 = [], S1 = [], F2 = [...ssa], F1 = [];
for (const [n, c] of census) (c >= 1000 ? S2 : S1).push(n);
for (const n of listSur) if (!census.has(n)) S1.push(n);
for (const n of listFirst) if (!ssa.has(n)) F1.push(n);
const tiers = { S2, S1, F2, F1, EN: english };
for (const k of Object.keys(tiers)) tiers[k] = [...new Set(tiers[k])].sort();

const js = `/* Infusion De-ID — large name lexicon (generated by tools/build-lexicon.js; do not edit by hand)
 * Sources: US Census 2000 surnames, SSA baby names 1880-2008, smashew/NameDatabases, google-10000-english (20k).
 * Tiers: S2 strong surname, S1 weak surname, F2 strong first name, F1 weak first name, EN English words. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.DeIDBigLex = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const S = (s) => new Set(s.split(' '));
  return {
${Object.entries(tiers).map(([k, arr]) => `    ${k}: S(${JSON.stringify(arr.join(' '))}),`).join('\n')}
  };
});
`;
fs.writeFileSync(path.join(root, 'src/biglex.js'), js);
console.log(`biglex: ${Object.entries(tiers).map(([k, a]) => `${k} ${a.length}`).join('  ')} -> ${(Buffer.byteLength(js) / 1024).toFixed(0)} KB`);
