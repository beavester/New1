#!/usr/bin/env node
/* Build src/clinvocab.js: the clinical vocabulary the strict pass consults before it reads an unknown capitalised word as
 * a name (see vendor/clinical/README.md for the sources, all CC0).
 *   drugs:    single words of brand and generic drug names
 *   suffixes: generic-name stems written at the end of a name (USAN: -tinib, -parin, -citabine, ...), five letters or more
 *             (the shorter ones the engine trusts are its own short list), without those that also end surnames
 *   prefixes: stems written at the start (cef-, sulfa-, gado-, ...), without those that also start names
 *   makes:    car manufacturers (a make after a colour or beside a vehicle word is a car, not a person)
 * A word in this file is kept in the output, so every entry that is also an ordinary word (useless) or a name of any tier
 * (dangerous) is dropped here. Plain lists, no Bloom filter: a false positive would be a leaked name. */
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..');
const json = (f) => JSON.parse(fs.readFileSync(path.join(root, 'vendor/clinical', f), 'utf8'));
const BIG = require(path.join(root, 'src/biglex.js'));
const english = new Set(fs.readFileSync(path.join(root, 'vendor/names/english-words.txt'), 'utf8').split(/\r?\n/).map((w) => w.trim().toLowerCase()).filter(Boolean));
const isName = (w) => BIG.S2.has(w) || BIG.S1.has(w) || BIG.F2.has(w) || BIG.F1.has(w);
const drugs = new Set();
for (const name of json('drugs.json').drugs) {
  for (const w of String(name).toLowerCase().split(/[^a-z]+/)) {
    if (w.length < 4 || english.has(w) || BIG.EN.has(w) || isName(w)) continue;
    drugs.add(w);
  }
}
const stems = json('drugNameStems.json').stems.map((s) => String(s).toLowerCase().trim()).filter((s) => /^-?[a-z]+-?$/.test(s));
// stems that are also the ending (or the start) of surnames and given names the lexicon may not hold (Kalim, Moren, Berel, Gillin, Guan-)
const NAME_SHAPED = /^(?:clone|pride|prost|meline|moren|panel|orphan|onium|toran|sonan|casan|kalim|ganan|antel|gillin|giline|kiren|berel|ermin|bermin|dermin|fermin|nermin|sermin|termin|arone|astine|mantine|troline|retin|serod|entan|butan|bulin|mulin|relin|siban|sulam|aril|guan|pred|trop|arte|estr)$/;
const suffixes = [...new Set(stems.filter((s) => s.startsWith('-') && !s.endsWith('-')).map((s) => s.slice(1)).filter((s) => s.length >= 5 && !NAME_SHAPED.test(s)))].sort();
const prefixes = [...new Set(stems.filter((s) => s.endsWith('-') && !s.startsWith('-')).map((s) => s.slice(0, -1)).filter((s) => (s.length >= 4 || s === 'cef') && !NAME_SHAPED.test(s)))].sort();
const makes = [...new Set(json('cars.json').cars.flatMap((c) => String(c).toLowerCase().split(/[^a-z]+/)).filter((w) => w.length >= 2 && !/^(?:motors|automobili|rover|land|martin|gordon|murray|smart|seat|mini|noble|morgan|proton|lotus|tata|romeo|alfa|royce|rolls|benz)$/.test(w)))].sort();
const body = `/* Infusion De-ID — clinical vocabulary for the strict pass (generated by tools/build-clinvocab.js from dariusk/corpora, CC0; do not edit) */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.DeIDClinVocab = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  return {
    drugs: ${JSON.stringify([...drugs].sort().join(' '))}.split(' '),
    suffixes: ${JSON.stringify(suffixes.join(' '))}.split(' '),
    prefixes: ${JSON.stringify(prefixes.join(' '))}.split(' '),
    makes: ${JSON.stringify(makes.join(' '))}.split(' '),
  };
});
`;
fs.writeFileSync(path.join(root, 'src/clinvocab.js'), body);
console.log(`src/clinvocab.js: ${drugs.size} drug words, ${suffixes.length} suffix stems, ${prefixes.length} prefix stems, ${makes.length} car makes (${(Buffer.byteLength(body) / 1024).toFixed(1)} KB)`);
