#!/usr/bin/env node
/* Build src/places.js: three Bloom filters over the US place lists in vendor/places/ (see vendor/places/README.md).
 *   names: every city, town, village and post-office place name, normalised (lower case, "St"/"Ft"/"Mt" spelled out,
 *          hyphens and apostrophes folded), in every spelling the list gives ("Mc Kinney" and "McKinney").
 *   major: the names of the 1,000 most populous cities, to settle a name that is also a common surname (Rochester, Durham).
 *   pairs: "name|ST" for every place and the state it is in, so "Reading, PA" can be told from "Smith, PA".
 * Unlike the dictionary filter, a false positive here is an over-redaction, so the name filter is built at 1 in 10,000.
 * The pair filter is only consulted for a name the name filter already holds, so 1 in 100 is enough for it. */
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, 'vendor/places', f), 'utf8').split(/\r?\n/).slice(1).filter(Boolean);
// the same normalisation is shipped in src/places.js and applied to the text at lookup
const norm = (s) => String(s || '').toLowerCase().replace(/[.'’`]/g, '').replace(/[-\/]+/g, ' ').replace(/\s+/g, ' ').trim()
  .replace(/\bst\b/g, 'saint').replace(/\bft\b/g, 'fort').replace(/\bmt\b/g, 'mount');
const csv = (line) => { const out = []; let cur = '', q = false; for (const ch of line) { if (ch === '"') q = !q; else if (ch === ',' && !q) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out; };
const names = new Set(), pairs = new Set(), major = new Set(), stateOf = {};
const add = (name, st, big) => {
  const n = norm(name); const words = n.split(' ');
  if (!/^[a-z][a-z ]+$/.test(n) || n.length < 3 || words.length > 4) return;
  const forms = [n];
  if (/^(?:mc|mac|de|du|la|le|o) [a-z]/.test(n) && words.length === 2) forms.push(words.join('')); // "Mc Kinney" is written McKinney, "De Kalb" DeKalb
  for (const f of forms) { names.add(f); if (st) pairs.add(`${f}|${st}`); if (big) major.add(f); }
};
// 1. kelvins/US-Cities-Database (MIT): ID,STATE_CODE,STATE_NAME,CITY,COUNTY,LATITUDE,LONGITUDE
for (const line of read('us_cities.csv')) { const c = csv(line); if (c.length < 5 || !/^[A-Z]{2}$/.test(c[1])) continue; stateOf[c[2].toLowerCase()] = c[1]; add(c[3], c[1]); }
// 2. plotly/datasets us-cities-top-1k.csv (MIT): City,State,Population,lat,lon — adds the large suburbs that have no post office of their own
for (const line of read('us-cities-top-1k.csv')) {
  const c = csv(line); const st = stateOf[(c[1] || '').toLowerCase()]; if (!st) continue;
  for (const part of c[0].split(/[()]/).map((x) => x.trim()).filter(Boolean)) add(part, st, true);
}
const bloom = (keys, p) => {
  const n = keys.length; const m = Math.ceil(-n * Math.log(p) / (Math.LN2 * Math.LN2)); const k = Math.round((m / n) * Math.LN2);
  const bits = new Uint8Array(Math.ceil(m / 8));
  const h1 = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; };
  const h2 = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = (Math.imul(h, 33) ^ s.charCodeAt(i)) >>> 0; return (h | 1) >>> 0; };
  for (const w of keys) { const a = h1(w), b = h2(w); for (let i = 0; i < k; i++) { const x = (a + Math.imul(i, b)) >>> 0; const bit = x % m; bits[bit >> 3] |= 1 << (bit & 7); } }
  return { m, k, b64: Buffer.from(bits).toString('base64') };
};
const N = bloom([...names], 1e-4), P = bloom([...pairs], 1e-2), M = bloom([...major], 1e-4);
const js = `/* Infusion De-ID — US place names (generated by tools/build-places.js from vendor/places/: kelvins/US-Cities-Database and plotly/datasets us-cities-top-1k, both MIT; do not edit) */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.DeIDPlaces = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const N = { m: ${N.m}, k: ${N.k}, b64: '${N.b64}', bits: null };
  const P = { m: ${P.m}, k: ${P.k}, b64: '${P.b64}', bits: null };
  const M = { m: ${M.m}, k: ${M.k}, b64: '${M.b64}', bits: null };
  const load = (f) => { if (f.bits) return f.bits; const s = typeof atob === 'function' ? atob(f.b64) : Buffer.from(f.b64, 'base64').toString('binary'); f.bits = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) f.bits[i] = s.charCodeAt(i); f.b64 = ''; return f.bits; };
  const h1 = (s) => { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; };
  const h2 = (s) => { let h = 5381; for (let i = 0; i < s.length; i++) h = (Math.imul(h, 33) ^ s.charCodeAt(i)) >>> 0; return (h | 1) >>> 0; };
  const test = (f, w) => { const b = load(f); const a = h1(w), c = h2(w); for (let i = 0; i < f.k; i++) { const x = (a + Math.imul(i, c)) >>> 0; const bit = x % f.m; if (!(b[bit >> 3] & (1 << (bit & 7)))) return false; } return true; };
  const norm = (s) => String(s || '').toLowerCase().replace(/[.'’\`]/g, '').replace(/[-\\/]+/g, ' ').replace(/\\s+/g, ' ').trim()
    .replace(/\\bst\\b/g, 'saint').replace(/\\bft\\b/g, 'fort').replace(/\\bmt\\b/g, 'mount');
  // has("Cedar Rapids"): a US place of that name exists. hasPair("Reading", "PA"): that place is in that state.
  const has = (name) => { const n = norm(name); return n.length >= 3 && test(N, n); };
  const hasPair = (name, st) => { const n = norm(name); return n.length >= 3 && /^[A-Za-z]{2}$/.test(st || '') && test(N, n) && test(P, n + '|' + String(st).toUpperCase()); };
  // isMajor("Rochester"): one of the 1,000 most populous US cities has that name.
  const isMajor = (name) => { const n = norm(name); return n.length >= 3 && test(N, n) && test(M, n); };
  return { has, hasPair, isMajor, norm, size: ${names.size}, pairs: ${pairs.size}, major: ${major.size}, maxWords: 4 };
});
`;
fs.writeFileSync(path.join(root, 'src/places.js'), js);
console.log(`places: ${names.size} names (m=${N.m}, k=${N.k}), ${pairs.size} name|state pairs (m=${P.m}, k=${P.k}), ${major.size} major, ${(Buffer.byteLength(js) / 1024).toFixed(0)} KB`);
